  String t(String key) {
    final localizedStrings = _strings[locale.languageCode];
    if (localizedStrings != null && localizedStrings.containsKey(key)) {
      return localizedStrings[key] ?? key;
    }
    return _strings['en']?[key] ?? key;
  }

  /// Человекочитаемое описание ошибки подключения по машинному коду.
  String connectionError(String? code) {
    final key = switch (code) {
      'unsupported_protocol' => 'protocolNotSupported',
      'vpn_permission_denied' => 'vpnPermissionDenied',
      'invalid_config' => 'invalidConfig',
      'tunnel_start_failed' => 'tunnelStartFailed',
      'native_unavailable' => 'nativeUnavailable',
      'busy' => 'vpnBusy',
      _ => 'connectionFailed',
    };
    return t(key);
  }
